    shutil.copy2(REPO/f'Uni-Mol-{d}.csv',REF/f'Uni-Mol-{d}.csv');sums.append(f"{hashlib.sha256((REF/f'Uni-Mol-{d}.csv').read_bytes()).hexdigest()}  references/primary/Uni-Mol-{d}.csv")
